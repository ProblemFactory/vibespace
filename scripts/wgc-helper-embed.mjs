#!/usr/bin/env node
// int304 (lane stream-p2w-build's helper, the Mac helper's way — scripts/mac-helper-embed.mjs): THE WINDOWS WINDOW HELPER'S
// SOURCE INTO THE AGENT BUNDLE — writes src/agentd/wgc-helper-source.js from tools/vibespace-wgc/vibespace-wgc.cs (run it after
// editing the C#; scripts/test-stream-window.mjs fails while the two differ). A plain module, so EVERY esbuild of the agent
// (the build's and each suite's own) carries the text with no loader flag; the agent builds the helper ON the machine from it
// (src/agentd/stream-window-source.js — its stamp is the text's sha256, so a changed source rebuilds).
//   node scripts/wgc-helper-embed.mjs            write the module
//   node scripts/wgc-helper-embed.mjs --check    exit 1 when the module is stale
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const REPO = path.resolve(new URL('..', import.meta.url).pathname);
const SRC = path.join(REPO, 'tools/vibespace-wgc/vibespace-wgc.cs');
const OUT = path.join(REPO, 'src/agentd/wgc-helper-source.js');

export function moduleText(source) {
  const sha = crypto.createHash('sha256').update(source).digest('hex');
  const lines = source.split('\n');
  return ["'use strict';",
    '// GENERATED by scripts/wgc-helper-embed.mjs from tools/vibespace-wgc/vibespace-wgc.cs — never edit by hand',
    '// (scripts/test-stream-window.mjs fails while the two differ). The Windows window helper rides the agent bundle as TEXT:',
    '// the agent builds it on the machine with its own csc (src/agentd/stream-window-source.js).',
    `const LINES = [\n${lines.map((l) => '  ' + JSON.stringify(l) + ',').join('\n')}\n];`,
    `module.exports = { SHA256: ${JSON.stringify(sha)}, SOURCE: LINES.join('\\n') };`, ''].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const want = moduleText(fs.readFileSync(SRC, 'utf8'));
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (have === want) { console.log('wgc-helper-source.js is current'); process.exit(0); }
    console.error('wgc-helper-source.js is STALE — run node scripts/wgc-helper-embed.mjs'); process.exit(1);
  }
  fs.writeFileSync(OUT, want);
  console.log(`wrote ${path.relative(REPO, OUT)} (${want.length} bytes)`);
}
