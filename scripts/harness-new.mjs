/** THE PLAN, in memory: the new files and the edited files a census-green add needs. `ctx` reads the tree (or a test's
 *  overrides). Returns { names, writes, edits, kinds } — kinds = the row kinds whose rows were written. */
export function plan(o, ctx) {
  const d = descriptorOf(o), names = harnessNames(d);
  const writes = {}; const edits = {}; const kinds = [];
  for (const [rel, text] of Object.entries(skeletons(o))) if (!ctx.exists(rel)) writes[rel] = text;
  const files = [...ctx.files, ...Object.keys(writes).filter((f) => /\.(?:m?js|cjs)$/.test(f) && !ctx.files.includes(f))];
  const read = (rel) => (Object.prototype.hasOwnProperty.call(edits, rel) ? edits[rel] : Object.prototype.hasOwnProperty.call(writes, rel) ? writes[rel] : ctx.read(rel));
  const exists = (rel) => Object.prototype.hasOwnProperty.call(writes, rel) || ctx.exists(rel);
  const pctx = { ...ctx, files, read, exists, names: [...ctx.names, names], builtin: [...ctx.builtin, names.id], memo: {} };
  for (const k of ROW_KINDS) {
    if (!k.applies(names, pctx) || !k.check(names, pctx).length || typeof k.insert !== 'function') continue;
    const targets = typeof k.file === 'function' ? [k.file(names)] : Array.isArray(k.file) ? k.file : [k.file];
    for (const rel of targets) {
      if (k.kind === 'brand-svg') { if (!exists(rel)) writes[rel] = k.insert(names); continue; }
      const cur = read(rel);
      if (cur == null) continue;
      const next = k.insert(names, cur, pctx);
      if (next !== cur) edits[rel] = next;
    }
    kinds.push(k.kind);
  }
  return { names, writes, edits, kinds };
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  const o = parseArgs(process.argv.slice(2));
  const repo = o.repo;
  const files = scanSet(repo);
  const H0 = loadRegistry(repo);
  if (H0.has(o.id)) { console.error(`harness '${o.id}' is already registered`); process.exit(2); }
  const ctx = {
    repo, files,
    read: (rel) => { try { return fs.readFileSync(path.join(repo, rel), 'utf8'); } catch { return null; } },
    exists: (rel) => fs.existsSync(path.join(repo, rel)),
    names: H0.list().map(harnessNames), builtin: H0.ids().filter((id) => H0.isBuiltin(id)), memo: {},
  };
  const p = plan(o, ctx);
  console.log(`harness ${o.id} (${o.label}, ${o.kind}): ${Object.keys(p.writes).length} new file(s), ${Object.keys(p.edits).length} edited file(s), row kinds ${p.kinds.join(' · ')}`);
  for (const rel of Object.keys(p.writes)) console.log(`  + ${rel}`);
  for (const rel of Object.keys(p.edits)) console.log(`  ~ ${rel}`);
  if (o.dryRun) { console.log('(dry run: nothing written)'); process.exit(0); }
  const tracked = new Set(trackedFiles(repo, 'src', 'scripts', 'public', 'docs', 'data/bin'));
  for (const [rel, text] of Object.entries(p.edits)) if (!tracked.has(rel)) { console.error(`refusing to edit an untracked file: ${rel}`); process.exit(2); }
  for (const [rel, text] of [...Object.entries(p.writes), ...Object.entries(p.edits)]) {
    const abs = path.join(repo, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, text, { mode: rel.startsWith('data/bin/') || rel.startsWith('scripts/test-') ? 0o755 : 0o644 });
  }
  // the own suite measured, its ci.mjs row's time filled (the tier rule wants a measured `in-process · <n> s`)
  const suite = `scripts/test-${o.id}-harness.mjs`;
  if (p.writes[suite]) {
    const t0 = Date.now(); const r = spawnSync(process.execPath, [path.join(repo, suite)], { cwd: repo, encoding: 'utf8' }); const ms = Date.now() - t0;
    const ci = path.join(repo, 'scripts/ci.mjs'); fs.writeFileSync(ci, fs.readFileSync(ci, 'utf8').replace('in-process · <measure> s', `in-process · ${(ms / 1000).toFixed(1)} s`));
    console.log(`  ${suite}: ${r.status === 0 ? 'ALL PASS' : 'RED'} in ${ms} ms (the ci.mjs row carries it)`);
  }
  // the census over the tree as it now is — in a FRESH process (this one's require cache holds the registry as it was;
  // the new descriptor arrives through index.js's require line)
  const c = spawnSync(process.execPath, [path.join(repo, 'scripts/harness-fences.mjs'), repo], { cwd: repo, encoding: 'utf8', maxBuffer: 1 << 26 });
  console.log('\nWHAT IS LEFT (the census over the tree you now have):');
  console.log((c.stdout || '').split('\n').map((l) => '  ' + l).join('\n'));
  if (c.stderr) console.error(c.stderr.slice(0, 2000));
  const r = { ok: c.status === 0 };
  console.log(`\nFIRST the product's own tables (src/backend-caps.js, src/lib/agent-meta.js, src/harness-settings.js …): scripts/test-harness-contract.mjs reads a harness's caps + META rows before it can list the rest of its TODOs.`);
  console.log(`\nSTAYS MANUAL: the protocol wrapper (${o.wrapper || 'none — a terminal'}) when the CLI is not ACP; the accounts / login / usage hooks (creds, quota, billingIdentity); the measured fixture (scripts/fixtures/${o.id}-cli/); the stream shapes the normalizer reads. Then: node scripts/test-harness-contract.mjs · node scripts/test-harness-add-census.mjs · npm run build.`);
  process.exit(r.ok ? 0 : 1);
}
