// Writes into the checkout it RUNS IN (--repo or the cwd; never a path bound from import.meta.url — test-architecture §51):
//   · src/harnesses/<id>.js — the descriptor skeleton: the REQUIRED keys filled, every hook a TODO naming the contract
//     (scripts/test-harness-contract.mjs) that will judge it; chat = an own adapter stub (src/adapters/<id>.js) over the
//     shared ACP journal pieces, acp = acpHarness({...}) as opencode, pty = a terminal-only descriptor as shell;
//   · data/bin/<wrapper> (a stub when absent), scripts/fixtures/<id>-cli/README.md (where the MEASURED fixture goes),
//     scripts/test-<id>-harness.mjs (the harness's own fast suite, a skeleton that passes);
//   · EVERY row the census's ROW KINDS derive, through their own `insert` (scripts/harness-fences.mjs — one source of truth,
//     never a second list): the cli-registry EXCLUDED row, the peer-text DECLARED_CLIS row, public/brand/<id>.svg, the
//     i18n keys (zh + ja), the New Session <option>, the scripts/ci.mjs row, the kb-features table rows, the registry's
//     require line.
// Then it runs the census and prints what is LEFT — the id-keyed TABLES whose rows carry judgment no generator should fake
// (BACKEND_CAPS, BACKEND_META, HARNESS_SETTINGS, the suites' rosters …) — and what stays manual: the protocol wrapper when
// the CLI is not ACP, the accounts / login / usage hooks, the measured fixture, the stream shapes.
