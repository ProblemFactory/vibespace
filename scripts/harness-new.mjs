const KINDS = ['chat', 'acp', 'pty'];
export function parseArgs(argv) {
  const o = { id: null, label: null, kind: 'chat', wrapper: null, program: null, repo: process.cwd(), dryRun: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--label') o.label = argv[++i];
    else if (a === '--kind') o.kind = argv[++i];
    else if (a === '--wrapper') o.wrapper = argv[++i];
    else if (a === '--program') o.program = argv[++i];
    else if (a === '--repo') o.repo = path.resolve(argv[++i]);
    else if (a === '--dry-run') o.dryRun = true;
    else if (!a.startsWith('--') && !o.id) o.id = a;
    else throw new Error(`unknown argument ${a}`);
  }
  if (!o.id || !/^[a-z][a-z0-9-]*$/.test(o.id)) throw new Error('an id is required: a lowercase slug (the registry\'s rule)');
  if (!o.label) throw new Error('--label "<label>" is required (the words a person reads)');
  if (!KINDS.includes(o.kind)) throw new Error(`--kind must be ${KINDS.join('|')}`);
  if (o.kind !== 'pty' && !o.wrapper) throw new Error('--wrapper data/bin/<file> is required for a chat / acp harness (the file the server spawns the session through)');
  if (o.wrapper && !/^data\/bin\/[\w.-]+$/.test(o.wrapper)) throw new Error('--wrapper must be a data/bin/<file> path');
  if (!o.program) o.program = o.id;
  return o;
}
const cap = (s) => s.replace(/(^|-)([a-z])/g, (m, d, c) => c.toUpperCase());

/** The descriptor the ROW KINDS read (the same names the skeleton declares). */
export function descriptorOf(o) {
  const terminal = o.kind === 'pty';
  return { id: o.id, label: o.label, kind: terminal ? 'terminal' : 'chat', wrapper: terminal ? null : o.wrapper, ...(terminal ? {} : { exe: { command: o.program }, brand: `/brand/${o.id}.svg` }) };
}

