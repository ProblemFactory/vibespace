#!/usr/bin/env node
// lane stream-mic-road (the window helper's way — scripts/wgc-helper-embed.mjs): THE MICROPHONE HELPERS' SOURCES INTO THE
// AGENT BUNDLE — writes src/mic-helper-source.js from tools/vibespace-mic/ (the Windows helper's C#, the Mac helper's Swift,
// the Mac plug-in's C + Info.plist). Run it after editing any of them; scripts/test-stream-mic-op.mjs fails while they differ.
// A plain module, so every esbuild of the agent carries the text with no loader flag; the agent builds each ON the machine
// (src/desktop-mic.js — a stamp per source digest, so a changed source rebuilds).
//   node scripts/mic-helper-embed.mjs            write the module
//   node scripts/mic-helper-embed.mjs --check    exit 1 when the module is stale
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const REPO = path.resolve(new URL('..', import.meta.url).pathname);
export const FILES = Object.freeze({ WIN: 'tools/vibespace-mic/vibespace-mic.cs', MAC: 'tools/vibespace-mic/vibespace-mic.swift', PLUGIN_C: 'tools/vibespace-mic/VibeSpaceMic.c', PLUGIN_PLIST: 'tools/vibespace-mic/VibeSpaceMic-Info.plist' });
const OUT = path.join(REPO, 'src/mic-helper-source.js');

export function moduleText(texts) {
  const out = ["'use strict';",
    '// GENERATED by scripts/mic-helper-embed.mjs from tools/vibespace-mic/ — never edit by hand (scripts/test-stream-mic-op.mjs',
    '// fails while the two differ). The microphone helpers ride the agent bundle as TEXT: the agent builds each on the machine',
    '// (src/desktop-mic.js — Windows: the in-box csc; a Mac: swiftc for the helper, clang for the plug-in). PURE: data only.'];
  const names = Object.keys(FILES);
  for (const k of names) {
    const lines = String(texts[k]).split('\n');
    out.push(`const ${k} = [\n${lines.map((l) => '  ' + JSON.stringify(l) + ',').join('\n')}\n].join('\\n');`);
  }
  const sha = (k) => crypto.createHash('sha256').update(String(texts[k])).digest('hex');
  out.push(`const SHA256 = Object.freeze({ ${names.map((k) => `${k}: ${JSON.stringify(sha(k))}`).join(', ')} });`);
  out.push(`module.exports = { ${names.join(', ')}, SHA256 };`, '');
  return out.join('\n');
}
export const readTexts = () => Object.fromEntries(Object.entries(FILES).map(([k, f]) => [k, fs.readFileSync(path.join(REPO, f), 'utf8')]));

if (import.meta.url === `file://${process.argv[1]}`) {
  const want = moduleText(readTexts());
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (have === want) { console.log('mic-helper-source.js is current'); process.exit(0); }
    console.error('mic-helper-source.js is STALE — run node scripts/mic-helper-embed.mjs'); process.exit(1);
  }
  fs.writeFileSync(OUT, want);
  console.log(`wrote ${path.relative(REPO, OUT)} (${want.length} bytes)`);
}
