#!/usr/bin/env node
// lane stream-p3m-build: THE MAC SCREEN HELPER'S SOURCE INTO THE AGENT BUNDLE — writes src/agentd/mac-helper-source.js from
// tools/vibespace-screen/vibespace-screen.swift (run it after editing the Swift; scripts/test-stream-mac.mjs fails while the
// two differ). The agent builds the helper ON the Mac from this text (src/agentd/stream-mac.js); the release builds the same
// text into the prebuilt (scripts/build-mac-helper.sh). VERSION = 'vs-' + the first 12 hex of the source's sha256: it moves
// only when the source does — an ad-hoc helper's Screen Recording grant is keyed to its path + cdhash, so a helper rebuilt
// for an agent update that never touched it would cost the owner a re-grant for nothing.
//   node scripts/mac-helper-embed.mjs            write the module
//   node scripts/mac-helper-embed.mjs --check    exit 1 when the module is stale (prints both versions)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const REPO = path.resolve(new URL('..', import.meta.url).pathname);
const SRC = path.join(REPO, 'tools/vibespace-screen/vibespace-screen.swift');
const OUT = path.join(REPO, 'src/agentd/mac-helper-source.js');

export function moduleText(source) {
  const sha = crypto.createHash('sha256').update(source).digest('hex');
  const lines = source.split('\n');
  return ["'use strict';",
    '// GENERATED by scripts/mac-helper-embed.mjs from tools/vibespace-screen/vibespace-screen.swift — never edit by hand',
    '// (scripts/test-stream-mac.mjs fails while the two differ). The paired Mac\'s screen helper rides the agent bundle as',
    '// TEXT: the agent builds it on the Mac (src/agentd/stream-mac.js); VERSION moves only when the source does.',
    `const LINES = [\n${lines.map((l) => '  ' + JSON.stringify(l) + ',').join('\n')}\n];`,
    `module.exports = { VERSION: ${JSON.stringify('vs-' + sha.slice(0, 12))}, SHA256: ${JSON.stringify(sha)}, SOURCE: LINES.join('\\n') };`, ''].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const want = moduleText(fs.readFileSync(SRC, 'utf8'));
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (have === want) { console.log('mac-helper-source.js is current'); process.exit(0); }
    console.error(`mac-helper-source.js is STALE — run node scripts/mac-helper-embed.mjs`); process.exit(1);
  }
  fs.writeFileSync(OUT, want);
  console.log(`wrote ${path.relative(REPO, OUT)} (${/VERSION: "([^"]+)"/.exec(want)[1]}, ${want.length} bytes)`);
}
