#!/usr/bin/env node
// TRANSCRIPT RETENTION (2.369.118, owner: "claude code 默认会删除旧对话…把默认值配成
// 100 年"): Claude Code sweeps transcripts older than cleanupPeriodDays (its own
// default 30) at every start. VibeSpace writes claude.transcriptRetentionDays
// (default 36500) into ~/.claude/settings.json through the hook installer's CAS
// writer — at boot, on change, and onto remote hosts through the shipped
// register helper (VIBESPACE_CLAUDE_KEEP_DAYS). Scratch dirs only; the real
// HOME is never touched. Run: node scripts/test-claude-retention.mjs
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { scratch } from './scratch.mjs';
const require = createRequire(import.meta.url);
const repo = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
let pass = 0, fail = 0;
const ok = (n, c, e) => { if (c) { pass++; console.log('  ✓ ' + n); } else { fail++; console.error('  ✗ ' + n + (e ? ' — ' + JSON.stringify(e) : '')); } };
const read = (f) => fs.readFileSync(path.join(repo, f), 'utf8');
const root = scratch('claude-retention');
fs.rmSync(root, { recursive: true, force: true });
fs.mkdirSync(path.join(root, 'data'), { recursive: true });
const { ensureClaudeRetention } = require(path.join(repo, 'src/server/agent-tool-generators.js')).create({ rootDir: root, port: 0 });

console.log('§1 ensureClaudeRetention on a scratch settings.json (never the real HOME)');
{
  const f = path.join(root, 'settings.json');
  fs.writeFileSync(f, JSON.stringify({ hooks: { Stop: [] }, permissions: { allow: ['Bash(ls:*)'] }, cleanupPeriodDays: 30 }, null, 2) + '\n');
  const r = ensureClaudeRetention(36500, { file: f });
  const j = JSON.parse(fs.readFileSync(f, 'utf8'));
  ok('36500 days written, everything else untouched', r.applied && r.changed && j.cleanupPeriodDays === 36500 && j.permissions.allow[0] === 'Bash(ls:*)' && Array.isArray(j.hooks.Stop), { r, j });
  const r2 = ensureClaudeRetention(36500, { file: f });
  ok('idempotent: the same value is not rewritten', r2.applied && r2.changed === false, r2);
  const r3 = ensureClaudeRetention('90', { file: f });
  ok('a string setting value is coerced; a change is written', r3.applied && r3.changed && JSON.parse(fs.readFileSync(f, 'utf8')).cleanupPeriodDays === 90, r3);
  const r0 = ensureClaudeRetention(0, { file: f });
  ok("0 = leave the CLI's own value alone ('off', nothing written)", r0.applied === false && r0.reason === 'off' && JSON.parse(fs.readFileSync(f, 'utf8')).cleanupPeriodDays === 90, r0);
  ok('NaN / negative / undefined are off too', ['x', -5, undefined, null].every((v) => ensureClaudeRetention(v, { file: f }).reason === 'off'));
  fs.writeFileSync(f, '{ not json');
  const rb = ensureClaudeRetention(36500, { file: f });
  ok('a hand-broken settings.json is refused by name, never overwritten', rb.applied === false && /not valid JSON/.test(rb.reason) && fs.readFileSync(f, 'utf8') === '{ not json', rb);
  const rm = ensureClaudeRetention(36500, { file: path.join(root, 'absent', 'settings.json') });
  ok('a missing settings.json is reported, not created (the CLI creates its own)', rm.applied === false && /not found/.test(rm.reason), rm);
}

console.log('§2 the shipped register helper carries VIBESPACE_CLAUDE_KEEP_DAYS to a remote HOME');
{
  const helper = path.join(root, 'data', 'bin', 'vibespace-hook-register.mjs');
  ok('the helper is generated by create()', fs.existsSync(helper));
  const home = path.join(root, 'home');
  fs.mkdirSync(path.join(home, '.claude'), { recursive: true });
  const sf = path.join(home, '.claude', 'settings.json');
  fs.writeFileSync(sf, JSON.stringify({ cleanupPeriodDays: 30, permissions: { allow: ['Read'] } }, null, 2));
  const run = (args, env) => execFileSync(process.execPath, [helper, ...args], { env: { ...process.env, HOME: home, ...env }, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
  run([], { VIBESPACE_CLAUDE_KEEP_DAYS: '36500' });
  let j = JSON.parse(fs.readFileSync(sf, 'utf8'));
  ok('install with the env: hooks registered AND cleanupPeriodDays lifted to 36500, permissions untouched', j.cleanupPeriodDays === 36500 && j.hooks && Array.isArray(j.hooks.Stop) && j.permissions.allow[0] === 'Read', j);
  run([], { VIBESPACE_CLAUDE_KEEP_DAYS: '36500' });
  ok('re-install is idempotent', JSON.parse(fs.readFileSync(sf, 'utf8')).cleanupPeriodDays === 36500);
  run([], { VIBESPACE_CLAUDE_KEEP_DAYS: '0' });
  ok('env 0 (setting off) leaves the value alone', JSON.parse(fs.readFileSync(sf, 'utf8')).cleanupPeriodDays === 36500);
  fs.writeFileSync(sf, JSON.stringify({ ...JSON.parse(fs.readFileSync(sf, 'utf8')), cleanupPeriodDays: 30 }, null, 2));
  run([], {});
  ok('no env (an older server) never touches it', JSON.parse(fs.readFileSync(sf, 'utf8')).cleanupPeriodDays === 30);
  run(['--uninstall'], { VIBESPACE_CLAUDE_KEEP_DAYS: '36500' });
  j = JSON.parse(fs.readFileSync(sf, 'utf8'));
  ok('--uninstall strips only our hook entries; retention is not rewritten by an uninstall', !(j.hooks && j.hooks.Stop && j.hooks.Stop.length) && j.cleanupPeriodDays === 30, j);
  const codexHooks = path.join(home, '.codex', 'hooks.json');
  ok('the codex hooks file never receives cleanupPeriodDays (a claude setting)', !fs.existsSync(codexHooks) || !('cleanupPeriodDays' in JSON.parse(fs.readFileSync(codexHooks, 'utf8'))));
}

console.log('§3 wiring pins (the 2.355.0 lesson: a pure fix without its call site is dead)');
{
  const srv = read('server.js'), schema = read('src/lib/settings-schema.js'), hosts = read('src/hosts.js');
  ok('settings-schema declares claude.transcriptRetentionDays (number, default 36500, category Claude)', /'claude\.transcriptRetentionDays': \{[\s\S]{0,700}default: 36500[\s\S]{0,900}category: t\('Claude'\)/.test(schema));
  ok('server.js syncs at boot (skipped under VIBESPACE_SKIP_AGENT_HOOKS, the worktree-smoke guard)', /if \(!process\.env\.VIBESPACE_SKIP_AGENT_HOOKS\) syncClaudeRetention\(\);/.test(srv));
  ok('server.js re-syncs when the setting changes (onSettingsWrite)', /\['claude\.transcriptRetentionDays'\] !== \(next \|\| \{\}\)\['claude\.transcriptRetentionDays'\]\) syncClaudeRetention\(\)/.test(srv));
  ok('the default when unset is 36500 (≈ 100 years), and the value is read through serverSetting', /function claudeKeepDays\(\) \{ const v = serverSetting\('claude\.transcriptRetentionDays'\);[^\n]*36500/.test(srv));
  ok('hosts.js hands the days to the remote register helper as VIBESPACE_CLAUDE_KEEP_DAYS', /VIBESPACE_CLAUDE_KEEP_DAYS=\$\{[^}]*claudeKeepDays[^}]*\}[^\n]*vibespace-hook-register\.mjs/.test(hosts) && /hosts\.claudeKeepDays = claudeKeepDays/.test(srv));
  const gen = read('src/server/agent-tool-generators.js');
  ok('the generator template reads the env and writes cleanupPeriodDays only into settings.json (never on --uninstall)', /const KEEP_DAYS = Math\.floor\(Number\(process\.env\.VIBESPACE_CLAUDE_KEEP_DAYS \|\| 0\)\)/.test(gen) && /KEEP_DAYS >= 1 && f\.endsWith\('settings\.json'\) && root\.cleanupPeriodDays !== KEEP_DAYS/.test(gen));
}

fs.rmSync(root, { recursive: true, force: true });
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
